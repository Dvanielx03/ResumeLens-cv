async page => {
  const base = 'http://localhost:8503';
  const assert = (condicion, mensaje) => { if (!condicion) throw new Error(mensaje); };
  const resultados = [];
  const errores = [];
  page.on('pageerror', error => errores.push(error.message));
  await page.setViewportSize({width:1440,height:1080});
  await page.goto(base);
  await page.getByRole('heading', {name:'ResumeLens',exact:true}).waitFor();
  await page.getByRole('button', {name:'Analizar CV',exact:true}).click();
  await page.getByText('Añade un CV válido y describe el puesto con al menos 40 caracteres.').waitFor();
  resultados.push('Entradas vacías: error visible, sin resultado inventado');
  await page.getByRole('button', {name:'Limpiar análisis',exact:true}).click();
  await page.screenshot({path:'docs/evidencias/01-inicio.png',fullPage:true});
  await page.getByRole('button', {name:'Ver ejemplo sin API',exact:true}).click();
  await page.getByText('89%', {exact:true}).waitFor();
  await page.getByText('Ejemplo ficticio · salida predefinida validada por LangChain. No se llamó a una API.').waitFor();
  await page.getByText('Experiencia relevante · 90/100', {exact:true}).click();
  await page.getByText('«Desarrollador Python con 3 anos de experiencia en aplicaciones web.»').waitFor();
  await page.screenshot({path:'docs/evidencias/02-resultado.png',fullPage:true});
  resultados.push('Ejemplo: 89%, desglose y cita literal visibles');
  const descarga = page.waitForEvent('download');
  await page.getByRole('button', {name:'Descargar informe',exact:true}).click();
  const archivo = await descarga;
  assert(archivo.suggestedFilename()==='resumelens-informe.md','Nombre de descarga incorrecto');
  await archivo.saveAs('output/resumelens-informe.md');
  resultados.push('Informe Markdown descargado');
  await page.getByRole('textbox', {name:'Contexto del puesto',exact:true}).fill('Puesto distinto: analista de datos con SQL, Python y visualizacion de indicadores.');
  await page.getByRole('textbox', {name:'Contexto del puesto',exact:true}).press('Tab');
  await page.getByText('Cambiaste las entradas. Vuelve a analizar para obtener un resultado actualizado.').waitFor();
  assert(await page.getByText('89%', {exact:true}).count()===0,'Se mostró resultado obsoleto');
  resultados.push('Cambiar el puesto oculta el resultado anterior');
  await page.getByRole('button', {name:'Limpiar análisis',exact:true}).click();
  await page.getByRole('heading', {name:'03 · Descubre el ajuste',exact:true}).waitFor();
  const input = page.locator('input[type=file]');
  await input.setInputFiles('ejemplos/cv_ejemplo.pdf');
  await page.getByText(/Documento leído/).waitFor();
  await page.getByRole('textbox', {name:'Contexto del puesto',exact:true}).fill('Desarrollador Python con 3 anos de experiencia en APIs REST y PostgreSQL; pruebas con pytest.');
  await page.getByRole('button', {name:'Analizar CV',exact:true}).click();
  await page.getByText('Autoriza el envío al proveedor para iniciar el análisis real.').waitFor();
  resultados.push('PDF real extraído y consentimiento exigido antes del proveedor');
  await page.getByText('Autorizo enviar el CV y el puesto al proveedor elegido', {exact:true}).click();
  assert(await page.getByRole('checkbox', {name:'Autorizo enviar el CV y el puesto al proveedor elegido'}).isChecked(), 'El consentimiento no se activó');
  await page.getByRole('button', {name:'Analizar CV',exact:true}).click();
  await page.getByText('Introduce una API key o configura la variable del proveedor en .env.').waitFor();
  await page.screenshot({path:'docs/evidencias/03-pdf-y-validacion.png',fullPage:true});
  resultados.push('Sin API key: error visible; no se fabrica una puntuación');
  await input.setInputFiles({name:'cv.txt',mimeType:'text/plain',buffer:Buffer.from('corto')});
  await page.getByText(/No hay suficiente texto extraíble/).waitFor();
  resultados.push('TXT insuficiente: se rechaza antes de la IA');
  await page.getByRole('button', {name:'Ver ejemplo sin API',exact:true}).click();
  await page.getByText('89%', {exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', {name:'Expand sidebar',exact:true}).waitFor();
  await page.waitForFunction(() => {
    const barra = document.querySelector('[data-testid="stSidebar"]');
    return !barra || barra.getBoundingClientRect().right <= 1;
  });
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Desbordamiento horizontal móvil');
  await page.getByText('89%', {exact:true}).scrollIntoViewIfNeeded();
  const caja = await page.getByText('89%', {exact:true}).boundingBox();
  assert(caja && caja.x >= 0 && caja.x + caja.width <= 390, 'Porcentaje recortado en móvil');
  await page.screenshot({path:'docs/evidencias/04-movil.png',fullPage:true});
  resultados.push('390px: resultado disponible sin desbordamiento horizontal');
  await page.getByRole('button', {name:'Limpiar análisis',exact:true}).click();
  await page.getByRole('heading', {name:'03 · Descubre el ajuste',exact:true}).waitFor();
  assert(await page.getByRole('textbox',{name:'Contexto del puesto',exact:true}).inputValue()==='', 'Limpiar no borró el puesto');
  assert(await page.getByText('89%',{exact:true}).count()===0,'Limpiar no borró el resultado');
  assert(errores.length===0,'Errores JavaScript: '+errores.join('; '));
  resultados.push('Limpiar reinicia documento, contexto y análisis; cero errores JavaScript');
  await page.setViewportSize({width:1440,height:1080});
  return {estado:'PASS',casos:resultados.length,resultados,erroresJavaScript:errores};
}
